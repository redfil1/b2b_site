export interface LegalDoc {
  slug: string;
  title: string;
}

// Единый источник списка правовых документов — используется и в
// app/legal/[doc]/page.tsx (заголовок страницы + проверка, что slug существует,
// иначе 404), и в app/sitemap.ts (какие /legal/<slug> включать в карту сайта).
// Раньше это были два независимых списка, которые пришлось бы синхронизировать
// руками при каждом новом документе (найдено при самокритичном аудите, 2026-09-06) —
// теперь один. Список конкретных документов по-прежнему не зафиксирован
// архитектурой (Project_Structure.md называет только примеры "политика
// конфиденциальности, оферта и т.п.") — это список известных на сегодня
// документов, новый добавляется сюда же.
export const LEGAL_DOCS: LegalDoc[] = [
  { slug: "privacy", title: "Политика конфиденциальности" },
  { slug: "offer", title: "Публичная оферта" },
];

export function getLegalDocTitle(slug: string): string | undefined {
  return LEGAL_DOCS.find((doc) => doc.slug === slug)?.title;
}
