// Нормализация телефона для атрибута `href="tel:..."`: оставляет только "+" и цифры.
// Нужна, т.к. отображаемый номер в src/config/site.ts форматирован для чтения
// (пробелы, скобки, дефисы) и содержит служебный текст-заглушку — всё это в
// tel:-ссылку попадать не должно, иначе номер не наберётся корректно.
export function normalizePhoneForTel(phone: string): string {
  return phone.replace(/[^\d+]/g, "");
}
