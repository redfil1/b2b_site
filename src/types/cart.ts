// Снимок товара в корзине (Architecture.md, раздел 2.3; Project_Structure.md).
// Намеренно НЕ Product и не его подмножество через Pick/Omit — это не дублирующий тип
// в смысле правила "один тип, одно место" (см. Project_Structure.md, раздел "Правила"):
// корзина хранится в localStorage целиком на стороне клиента, поэтому фиксирует только
// то, что нужно показать в списке и передать менеджеру, а не весь Product
// (specs/images/documents и т.п. корзине не нужны и не должны туда попадать).
export interface CartItem {
  /** Уникальный ключ товара в корзине — равен Product.slug. */
  productSlug: string;
  /** Категория товара — нужна для ссылки на карточку (/catalog/[category]/[slug]). */
  category: string;
  /** Название на момент добавления в корзину (снимок, не обновляется при переименовании товара). */
  title: string;
  /** Модель производителя — не у всех товаров есть (Product.model опционален). */
  model?: string;
  /** Артикул/код товара у поставщика — не у всех товаров есть (Product.sku опционален). */
  sku?: string;
  quantity: number;
}
